import type { Readable } from 'node:stream';

export interface StoredObject {
  sizeBytes: number;
  /** Lowercase hex SHA-256 of the stored bytes. */
  sha256: string;
}

export class ObjectTooLargeError extends Error {
  constructor() {
    super('Object exceeds the permitted size');
    this.name = 'ObjectTooLargeError';
  }
}

export class ObjectNotFoundError extends Error {
  constructor() {
    super('Object not found');
    this.name = 'ObjectNotFoundError';
  }
}

export class InvalidStorageKeyError extends Error {
  constructor() {
    super('Invalid storage key');
    this.name = 'InvalidStorageKeyError';
  }
}

/**
 * Object storage abstraction (LLD §2.1 `storage`). All access goes through this service
 * (backend rule). Keys are generated by the application from IDs, never from user input.
 * `LocalStorageService` implements it for development; an S3 implementation maps
 * `writeObject` to multipart part uploads and `composeObject` to CompleteMultipartUpload.
 */
export abstract class StorageService {
  /** Streams `source` to `key` atomically. Rejects with ObjectTooLargeError past `maxBytes`. */
  abstract writeObject(
    key: string,
    source: Readable,
    opts: { maxBytes: number },
  ): Promise<StoredObject>;
  /** Concatenates `sourceKeys` in order into `destKey` atomically. */
  abstract composeObject(sourceKeys: readonly string[], destKey: string): Promise<StoredObject>;
  /** Reads up to `length` bytes from the start of the object. */
  abstract readHead(key: string, length: number): Promise<Buffer>;
  /** Size of the object. Rejects with ObjectNotFoundError if it does not exist. */
  abstract statObject(key: string): Promise<{ sizeBytes: number }>;
  /** Streams the object, or the inclusive byte range `[start, end]`. Rejects with ObjectNotFoundError. */
  abstract openReadStream(key: string, range?: { start: number; end: number }): Promise<Readable>;
  /** Deletes objects; missing objects are ignored. */
  abstract deleteObjects(keys: readonly string[]): Promise<void>;
  /** Opaque URI stored in the database (never shown to users). */
  abstract uriFor(key: string): string;
}

export const StorageKeys = {
  uploadPart: (recordingId: string, partNumber: number) =>
    `uploads/${recordingId}/parts/${String(partNumber).padStart(6, '0')}`,
  original: (workspaceId: string, recordingId: string) =>
    `recordings/${workspaceId}/${recordingId}/original`,
};
