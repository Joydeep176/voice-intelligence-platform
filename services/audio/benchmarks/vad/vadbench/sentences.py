# Voice per language group; sentences rotate through the group's voices by index.
VOICES = {
    "en": ["Aman", "Rishi", "Tara", "Daniel", "Fred", "Albert"],
    "hi": ["Lekha"],
    "hd": ["Lekha"],
    "hr": ["Aman", "Rishi", "Tara"],
}

# Reporting language of each group: Hinglish covers both code-switched kinds.
LANGUAGE = {"en": "english", "hi": "hindi", "hd": "hinglish", "hr": "hinglish"}


def all_sentences() -> list[dict[str, str]]:
    """Every sentence as `{id, group, language, voice, text}` in a fixed order."""
    out: list[dict[str, str]] = []
    for group, texts in (
        ("en", ENGLISH[:60]),
        ("hi", HINDI[:60]),
        ("hd", HINGLISH_DEVANAGARI),
        ("hr", HINGLISH_ROMAN),
    ):
        voices = VOICES[group]
        for i, text in enumerate(texts):
            out.append(
                {
                    "id": f"{group}-{i + 1:03d}",
                    "group": group,
                    "language": LANGUAGE[group],
                    "voice": voices[i % len(voices)],
                    "text": text,
                }
            )
    return out
